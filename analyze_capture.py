"""Turn a capture into a report and diff it against the static contract.

  python3 analyze_capture.py [captures_dir] [--out docs/capture-report.md]

Reads the JSONL produced by device-setup/capture-addon.py and writes:
  * per endpoint: calls, request keys, response keys, status codes, observed status fields
  * endpoints seen live that the static contract did not contain
  * request keys observed live that the static contract did not document
  * observed order-status values (book.status lifecycle evidence)
"""
import json
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.abspath(__file__))


OUR_API = {
    '/api/v1/auth/login': {'tel', 'pwd', 'device_id', 'app', 'v'},
    '/api/v1/config': set(),
    '/api/v1/driver/online': {'online'},
    '/api/v1/driver/gps': {'lat', 'lng', 'speed', 'bid'},
    '/api/v1/driver/risk': set(),
    '/api/v1/orders/available': {'lat', 'lng'},
    '/api/v1/orders/accept': {'bid'},
    '/api/v1/orders/arrived_pickup': {'bid'},
    '/api/v1/orders/start_ride': {'bid'},
    '/api/v1/orders/arrived_dropoff': {'bid'},
    '/api/v1/orders/complete': {'bid', 'tunnel'},
    '/api/v1/orders/cancel': {'bid'},
    '/api/v1/orders/report': {'bid', 'kind'},
    '/api/v1/orders/{bid}': set(),
}


def load_static():
    """endpoint -> {params:[...]} from the static extraction"""
    out = {k: {'params': set(v)} for k, v in OUR_API.items()}
    for f in ('c_drv4.json', 'c_pax4.json'):
        p = os.path.join(ROOT, f)
        if not os.path.exists(p):
            continue
        for row in json.load(open(p)):
            for path in row['paths']:
                e = out.setdefault(path, {'params': set()})
                e['params'] |= set(row['params'])
    return out


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    capdir = args[0] if args else os.path.join(ROOT, 'captures')
    outfile = os.path.join(ROOT, 'docs', 'capture-report.md')
    for i, a in enumerate(sys.argv):
        if a == '--out':
            outfile = sys.argv[i + 1]

    static = load_static()
    files = sorted([os.path.join(capdir, f) for f in os.listdir(capdir) if f.endswith('.jsonl')]) \
        if os.path.isdir(capdir) else []
    recs = []
    for f in files:
        for line in open(f, encoding='utf-8'):
            line = line.strip()
            if line:
                recs.append(json.loads(line))

    ep = defaultdict(lambda: {'n': 0, 'methods': set(), 'req': set(), 'resp': set(),
                              'status': set(), 'fields': defaultdict(set), 'hosts': set(),
                              'dpop': False, 'auth': False})
    for r in recs:
        e = ep[r['path']]
        e['n'] += 1
        e['methods'].add(r['method'])
        e['hosts'].add(r.get('host'))
        e['req'] |= set(r.get('req_keys') or [])
        e['resp'] |= set(r.get('resp_keys') or [])
        if r.get('status'):
            e['status'].add(str(r['status']))
        for k, v in (r.get('status_fields') or {}).items():
            e['fields'][k].add(str(v))
        e['dpop'] = e['dpop'] or bool(r.get('dpop'))
        e['auth'] = e['auth'] or bool(r.get('auth'))

    live = set(ep)
    new_eps = sorted(p for p in live if p not in static)
    extra_keys = {}
    for p in live:
        if p in static:
            diff = sorted(k for k in ep[p]['req'] if k not in static[p]['params'])
            if diff:
                extra_keys[p] = diff

    statuses = set()
    for p, e in ep.items():
        for k, vals in e['fields'].items():
            if k in ('status', 'status_code', 'book_status'):
                for v in vals:
                    if re.fullmatch(r'-?\d{1,3}', v):
                        statuses.add(v)

    L = ['# Capture report', '',
         f'Records: **{len(recs)}** from {len(files)} capture file(s) in `{capdir}`.',
         'Generated by `analyze_capture.py`. PII was already masked by the capture addon.', '',
         '## Endpoints observed', '',
         '| endpoint | calls | method | req keys | resp keys | http | DPoP | Bearer |',
         '|---|---|---|---|---|---|---|---|']
    for p in sorted(ep, key=lambda x: -ep[x]['n']):
        e = ep[p]
        L.append(f"| `{p}` | {e['n']} | {','.join(e['methods'])} | "
                 f"{', '.join('`'+k+'`' for k in sorted(e['req'])) or '—'} | "
                 f"{', '.join('`'+k+'`' for k in sorted(e['resp'])) or '—'} | "
                 f"{', '.join(e['status']) or '—'} | {'yes' if e['dpop'] else 'no'} | {'yes' if e['auth'] else 'no'} |")

    L += ['', '## Observed status values', '']
    if statuses:
        L.append('`order status` values seen in responses: ' + ', '.join(f'`{s}`' for s in sorted(statuses, key=lambda x: int(x))))
    else:
        L.append('_none observed in this capture_')

    L += ['', '## Live-only endpoints (not in the static contract)', '']
    L += [f'- `{p}` ({ep[p]["n"]} calls)' for p in new_eps] or ['_none_']

    L += ['', '## Request keys seen live but not in the static contract', '']
    if extra_keys:
        for p, ks in sorted(extra_keys.items()):
            L.append(f'- `{p}`: ' + ', '.join(f'`{k}`' for k in ks))
    else:
        L.append('_none — live traffic matched the statically recovered contract_')

    L += ['', '## Interpretation', '',
          '- Every request is POST unless noted; bodies are JSON (driver) or form-urlencoded (passenger).',
          '- `DPoP: yes` means the client sent an RFC 9449 DPoP proof; `Bearer: yes` means it sent an',
          '  access token header. Both are required by the production API and absent from our own server.',
          '- Order status values map onto the state machine in `product/spec/state-machine.md`.',
          '']
    os.makedirs(os.path.dirname(outfile), exist_ok=True)
    open(outfile, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print(f'{outfile}: {len(recs)} records, {len(ep)} endpoints, {len(new_eps)} live-only, '
          f'{len(extra_keys)} endpoints with undocumented keys')


if __name__ == '__main__':
    main()
